// coworkerd-launcher: starts one workerd process in its least-privilege environment, then
// becomes it.
//
// The Server starts it in place of workerd (node/process-pool.c++ spawn(), when the sandbox is on):
//
//   coworkerd-launcher [OPTION...] -- PROGRAM ARG...
//
// The options come from the command line only, never from the environment; everything after `--` is
// workerd's command line exactly as the Server would have started it, and the environment, the signal mask
// and the inherited descriptors 1-6 (output pipes, limit event pipe, listening socket, the two shared memory
// blocks) reach workerd untouched -- none of them is a path, so none is affected by the mount namespace.
// The interface (options, the status descriptor, exit codes) is described in PROTOCOL.md beside this file.
// The mechanisms: one unshare for the user, mount,
// network, IPC and UTS namespaces; a tmpfs root holding only the bound paths, pivot_root into it and the
// root remounted read-only; every capability dropped; no_new_privs; and a system call allowlist
// generated by the build from a profile of the workerd it ships, installed as the last step before the
// execv -- so it covers workerd itself, which is why the startup allowlist contains execve.
// An allowlist may name several workerd files (one `# workerd-sha256` line each): that is how an upgrade is
// prepared, since a list covering both binaries can be installed before the binary is replaced.
//
// Build: part of the Server's CMake build on Linux (target coworkerd-launcher).
